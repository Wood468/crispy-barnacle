#!/usr/bin/env python3
"""Builds public/moves.json from two published game-data files. Nothing is typed in by hand.
Usage: build-moves.py PVPOKE_MOVES.json PVPOKE_POKEMON.json POKEMINERS_LATEST.json GAMEMASTER_TIMESTAMP > public/moves.json
 types : PvPoke game master (github.com/pvpoke/pvpoke, src/data/gamemaster/moves.json), cross-checked against the PokeMiners game master.
 elite : PvPoke 'eliteMoves' per Pokémon (moves that need an Elite TM). Moves PvPoke lists as 'legacyMoves' (no longer obtainable) are excluded.
A move whose type depends on the Pokémon (Aura Wheel, Hidden Power) is left out of types and listed under ambiguous."""
import datetime, json, re, sys
mv = json.load(open(sys.argv[1])); pk = json.load(open(sys.argv[2])); pm = json.load(open(sys.argv[3])); stamp = sys.argv[4]
AMBIG = {"Aura Wheel": "Electric or Dark, depending on Morpeko's form", "Hidden Power": "Depends on the individual Pokémon", "Weather Ball": "Depends on the weather"}
ALIASES = {"Vice Grip": "Vise Grip"}   # spellings used by the app's own lists; lookups also ignore case, spaces and punctuation
SKIP = ("(Speculative)", "Fast Blastoise")
pmt = {}
for t in pm:
    if re.match(r"^COMBAT_V\d+_MOVE_", t.get("templateId", "")):
        c = t["data"]["combatMove"]; pmt[re.sub(r"^COMBAT_V\d+_MOVE_", "", t["templateId"]).replace("_FAST", "")] = c["type"].replace("POKEMON_TYPE_", "").lower()
types, single, fast, byid = {}, [], set(), {}
for m in mv:
    n = m["name"]; byid[m["moveId"]] = n
    if n.endswith("+") or n in AMBIG or any(x in n for x in SKIP): continue
    t = m["type"].capitalize()
    if n in types and types[n] != t: raise SystemExit("type conflict inside source: " + n)
    types[n] = t
    if m.get("energy", 1) == 0 and m.get("energyGain", 0) > 0: fast.add(n)
    p = pmt.get(m["moveId"])
    if p is None: single.append(n)
    elif p != m["type"]: raise SystemExit("sources disagree on " + n)
def key(name): return " ".join(sorted(re.findall(r"[a-z0-9]+", name.lower().replace("é", "e"))))
elite = {}
for x in pk:
    legacy = set(x.get("legacyMoves", []))
    names = sorted({byid[i] for i in x.get("eliteMoves", []) if i in byid and i not in legacy and not byid[i].endswith("+")})
    if names: elite.setdefault(key(x["speciesName"]), sorted(set(elite.get(key(x["speciesName"]), [])) | set(names)))
print(json.dumps({
  "source": {"types": {"name": "PvPoke game master", "url": "https://github.com/pvpoke/pvpoke/blob/master/src/data/gamemaster/moves.json", "crosscheck": "PokeMiners game master (github.com/PokeMiners/game_masters), same type for every move both list"},
             "elite": {"name": "PvPoke game master, eliteMoves per Pokémon (legacyMoves excluded)", "url": "https://github.com/pvpoke/pvpoke/blob/master/src/data/gamemaster/pokemon.json"},
             "observed": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d"), "generated": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"), "gamemaster": stamp, "how_to_update": "Run tools/refresh-moves.sh (downloads the source files, rebuilds this file, refuses to write if the sources disagree). Do not edit this file by hand.", "elite_note": "A move with no Elite TM tag means these sources do not list one. It does not prove the move cannot be obtained."},
  "types": dict(sorted(types.items())), "fast": sorted(fast), "singleSource": sorted(single), "ambiguous": AMBIG, "aliases": ALIASES,
  "elite": dict(sorted(elite.items()))}, ensure_ascii=False, separators=(",", ":")))
